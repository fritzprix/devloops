#!/usr/bin/env python3
"""Tests for issue_candidates.py and producer issue filtering (Rule 3)."""
import importlib.util
import sys
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

_script_path = REPO_ROOT / "skills" / "worker-loop" / "scripts" / "issue_candidates.py"
_spec = importlib.util.spec_from_file_location("worker_issue_candidates", _script_path)
_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_module)
filter_and_rank_issues = _module.filter_and_rank_issues


class IssueCandidatesRule3Test(unittest.TestCase):
    def setUp(self):
        self.me = "test-worker"
        self.open_prs = []

    def test_producer_issue_without_approved_is_excluded(self):
        issues = [
            {
                "number": 1,
                "title": "Automated security finding",
                "body": "Security issue detected",
                "labels": [{"name": "auto:producer"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            }
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me)
        self.assertEqual(len(result["candidates"]), 0)
        self.assertEqual(len(result["excluded"]), 1)
        self.assertEqual(result["excluded"][0]["number"], 1)
        self.assertIn("producer issue not approved", result["excluded"][0]["reason"])

    def test_producer_issue_with_approved_is_candidate(self):
        issues = [
            {
                "number": 2,
                "title": "Approved security finding",
                "body": "Security issue detected and human approved",
                "labels": [{"name": "auto:producer"}, {"name": "approved"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            }
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me)
        self.assertEqual(len(result["candidates"]), 1)
        self.assertEqual(result["candidates"][0]["number"], 2)
        self.assertEqual(len(result["excluded"]), 0)

    def test_non_producer_issue_is_candidate_without_approved(self):
        issues = [
            {
                "number": 3,
                "title": "User-filed bug",
                "body": "A bug reported by a user",
                "labels": [{"name": "bug"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            }
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me)
        self.assertEqual(len(result["candidates"]), 1)
        self.assertEqual(result["candidates"][0]["number"], 3)
        self.assertEqual(len(result["excluded"]), 0)

    def test_custom_producer_and_approved_labels_from_config(self):
        custom_config = {
            "labels": {
                "producer": "bot:generated",
                "approved": "human:approved",
            }
        }
        issues = [
            {
                "number": 4,
                "title": "Issue with custom producer label",
                "body": "Generated by bot",
                "labels": [{"name": "bot:generated"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            },
            {
                "number": 5,
                "title": "Issue with custom approved label",
                "body": "Generated by bot and approved",
                "labels": [{"name": "bot:generated"}, {"name": "human:approved"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            },
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me, config=custom_config)
        self.assertEqual(len(result["excluded"]), 1)
        self.assertEqual(result["excluded"][0]["number"], 4)
        self.assertEqual(len(result["candidates"]), 1)
        self.assertEqual(result["candidates"][0]["number"], 5)


if __name__ == "__main__":
    unittest.main()
