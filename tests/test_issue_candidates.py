_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_module)
filter_and_rank_issues = _module.filter_and_rank_issues


class IssueCandidatesRule3Test(unittest.TestCase):
    def setUp(self):
        self.me = "test-worker"
        self.open_prs = []

    def test_producer_issue_without_approved_is_excluded(self):
        issues = [
            {
                "number": 1,
                "title": "Automated security finding",
                "body": "Security issue detected",
                "labels": [{"name": "auto:producer"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            }
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me)
        self.assertEqual(len(result["candidates"]), 0)
        self.assertEqual(len(result["excluded"]), 1)
        self.assertEqual(result["excluded"][0]["number"], 1)
        self.assertIn("producer issue not approved", result["excluded"][0]["reason"])

    def test_producer_issue_with_approved_is_candidate(self):
        issues = [
            {
                "number": 2,
                "title": "Approved security finding",
                "body": "Security issue detected and human approved",
                "labels": [{"name": "auto:producer"}, {"name": "approved"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            }
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me)
        self.assertEqual(len(result["candidates"]), 1)
        self.assertEqual(result["candidates"][0]["number"], 2)
        self.assertEqual(len(result["excluded"]), 0)

    def test_non_producer_issue_is_candidate_without_approved(self):
        issues = [
            {
                "number": 3,
                "title": "User-filed bug",
                "body": "A bug reported by a user",
                "labels": [{"name": "bug"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            }
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me)
        self.assertEqual(len(result["candidates"]), 1)
        self.assertEqual(result["candidates"][0]["number"], 3)
        self.assertEqual(len(result["excluded"]), 0)

    def test_custom_producer_and_approved_labels_from_config(self):
        custom_config = {
            "labels": {
                "producer": "bot:generated",
                "approved": "human:approved",
            }
        }
        issues = [
            {
                "number": 4,
                "title": "Issue with custom producer label",
                "body": "Generated by bot",
                "labels": [{"name": "bot:generated"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            },
            {
                "number": 5,
                "title": "Issue with custom approved label",
                "body": "Generated by bot and approved",
                "labels": [{"name": "bot:generated"}, {"name": "human:approved"}],
                "assignees": [],
                "updatedAt": "2026-10-31T00:00:00Z",
            },
        ]
        result = filter_and_rank_issues(issues, self.open_prs, self.me, config=custom_config)
        self.assertEqual(len(result["excluded"]), 1)
        self.assertEqual(result["excluded"][0]["number"], 4)
        self.assertEqual(len(result["candidates"]), 1)
        self.assertEqual(result["candidates"][0]["number"], 5)


def _issue(number, body=""):
    return {"number": number, "title": f"Issue {number}", "body": body, "labels": [], "assignees": []}


def _pr(number, head, base="main", title="PR", body="", author="me", **fields):
    return {
        "number": number, "title": title, "body": body, "headRefName": head,
        "baseRefName": base, "author": {"login": author}, **fields,
    }


class DependencyTest(unittest.TestCase):
    def _candidates(self, issues, prs=()):
        result = filter_and_rank_issues(issues, list(prs), "me", config={})
        return {c["number"]: c for c in result["candidates"]}, [c["number"] for c in result["candidates"]]

    def test_parse_depends_on_reads_lines_only(self):
        body = (
            "Depends on #1\n"
            "- depends on: #2, #3 and #4\n"
            "The original issue depended on #5, and this depends on #6 in a sentence.\n"
            "DEPENDS ON #7\n"
            "Depends on #9\n"
        )
        self.assertEqual(_module.parse_depends_on(body, 9), [1, 2, 3, 4, 7])
        self.assertEqual(_module.parse_depends_on("no deps", 9), [])

    def test_no_dependency_and_closed_dependency(self):
        by_number, _ = self._candidates([_issue(10), _issue(11, "Depends on #99")])
        self.assertEqual(by_number[10]["dependency"]["status"], "none")
        self.assertEqual(by_number[11]["dependency"]["status"], "ready")

    def test_open_dependency_without_a_pr_waits_and_ranks_last(self):
        by_number, order = self._candidates([_issue(1), _issue(10, "Depends on #1"), _issue(11)])
        self.assertEqual(by_number[10]["dependency"]["status"], "wait")
        self.assertEqual(by_number[10]["dependency"]["open"], [1])
        self.assertIsNone(by_number[10]["dependency"]["stackOn"])
        self.assertEqual(order[-1], 10)

    def test_dependency_with_a_pr_can_stack_for_every_way_a_pr_links_to_it(self):
        prs = {
            "head suffix": _pr(20, "feat/x-1"),
            "closing keyword": _pr(20, "feat/x", body="Fixes #1"),
            "part of": _pr(20, "feat/x", body="Part of #1"),
        }
        for name, pr in prs.items():
            with self.subTest(name):
                # A closing PR excludes #1 itself, so #10 alone is the candidate under test.
                by_number, _ = self._candidates([_issue(1), _issue(10, "Depends on #1")], [pr])
                dependency = by_number[10]["dependency"]
                self.assertEqual(dependency["status"], "stack")
                self.assertEqual(dependency["stackOn"], {"pr": 20, "head": pr["headRefName"], "approved": False})

    def test_dependency_on_a_pr_number_stacks_on_it(self):
        by_number, _ = self._candidates([_issue(10, "Depends on #20")], [_pr(20, "feat/x")])
        self.assertEqual(by_number[10]["dependency"]["stackOn"]["pr"], 20)

    def test_an_approved_pr_is_offered_before_an_unapproved_one(self):
        prs = [
            _pr(20, "feat/old", body="Part of #1", reviewDecision="APPROVED"),
            _pr(21, "feat/new", body="Part of #1"),
        ]
        by_number, _ = self._candidates([_issue(1), _issue(10, "Depends on #1")], prs)
        self.assertEqual(by_number[10]["dependency"]["stackOn"], {"pr": 20, "head": "feat/old", "approved": True})

    def test_gatekeeper_label_counts_as_approved(self):
        prs = [_pr(20, "feat/x", body="Part of #1", labels=[{"name": "gatekeeper:approved"}])]
        by_number, _ = self._candidates([_issue(1), _issue(10, "Depends on #1")], prs)
        self.assertTrue(by_number[10]["dependency"]["stackOn"]["approved"])

    def test_a_stacked_pr_is_not_offered(self):
        # Stacking on it would reach depth 2.
        prs = [_pr(21, "feat/y", base="feat/x", body="Part of #1")]
        by_number, _ = self._candidates([_issue(1), _issue(10, "Depends on #1")], prs)
        self.assertEqual(by_number[10]["dependency"]["status"], "wait")

    def test_two_open_dependencies_wait_because_a_branch_has_one_base(self):
        prs = [_pr(20, "feat/x-1"), _pr(21, "feat/y-2")]
        by_number, _ = self._candidates([_issue(1), _issue(2), _issue(10, "Depends on #1\nDepends on #2")], prs)
        self.assertEqual(by_number[10]["dependency"]["status"], "wait")
        self.assertEqual(by_number[10]["dependency"]["open"], [1, 2])

    def test_rank_order_is_free_then_approved_stack_then_unapproved_stack_then_wait(self):
        issues = [_issue(1), _issue(2), _issue(3),
                  _issue(10, "Depends on #3"), _issue(11, "Depends on #2"), _issue(12, "Depends on #1"), _issue(13)]
        prs = [_pr(20, "feat/a", body="Part of #1"),
               _pr(21, "feat/b", body="Part of #2", reviewDecision="APPROVED")]
        _, order = self._candidates(issues, prs)
        self.assertLess(order.index(13), order.index(12))
        self.assertLess(order.index(11), order.index(12))
        self.assertLess(order.index(12), order.index(10))


class OpenPrLimitTest(unittest.TestCase):
    def test_counts_only_my_unapproved_prs(self):
        prs = [_pr(n, f"feat/{n}") for n in range(1, 5)] + [
            _pr(5, "feat/5", reviewDecision="APPROVED"),
            _pr(6, "feat/6", labels=[{"name": "gatekeeper:approved"}]),
            _pr(7, "feat/7", author="someone-else"),
        ]
        self.assertEqual(_module.open_pr_limit(prs, "me", 5), {"unapproved": 4, "limit": 5, "reached": False})

    def test_limit_comes_from_config(self):
        prs = [_pr(n, f"feat/{n}") for n in range(1, 4)]
        result = filter_and_rank_issues([], prs, "me", config={"worker": {"open_pr_limit": 3}})
        self.assertEqual(result["openPRLimit"], {"unapproved": 3, "limit": 3, "reached": True})

    def test_limit_is_reached_at_five(self):
        prs = [_pr(n, f"feat/{n}") for n in range(1, 6)]
        # Explicit config: the repo's own devloops.config.yaml may configure a
        # different limit, and the default itself is covered in test_config.py.
        result = filter_and_rank_issues([], prs, "me", config={"worker": {"open_pr_limit": 5}})
        self.assertEqual(result["openPRLimit"], {"unapproved": 5, "limit": 5, "reached": True})


class NeedsOwnerParkTest(unittest.TestCase):
    """Issue #67: a needs-owner parked issue gets no work until an owner answers."""

    me = "test-worker"

    def _issue(self, number, labels):
        return {
            "number": number,
            "title": f"Issue {number}",
            "body": "body",
            "labels": [{"name": name} for name in labels],
            "assignees": [],
            "updatedAt": "2026-10-31T00:00:00Z",
        }

    def _ask(self, loop="worker-loop", createdAt="2026-11-01T00:00:00Z"):
        return {
            "body": f"<!-- {loop}: needs-owner -->\n\nWhich API should we use?",
            "createdAt": createdAt,
            "author": {"login": self.me},
            "url": "https://example.test/c/ask",
        }

    def _reply(self, login, createdAt, body="Use API v2.", association=None):
        comment = {
            "body": body,
            "createdAt": createdAt,
            "author": {"login": login},
            "url": "https://example.test/c/reply",
        }
        if association:
            comment["authorAssociation"] = association
        return comment

    def _exclusion_reason(self, number, comments):
        result = filter_and_rank_issues(
            [self._issue(number, ["needs-owner"])], [], self.me,
            config={}, issue_comments={number: comments},
        )
        self.assertEqual(result["candidates"], [])
        excluded = {e["number"]: e for e in result["excluded"]}
        self.assertIn(number, excluded)
        return excluded[number]["reason"]

    def test_parked_needs_owner_issue_is_excluded(self):
        reason = self._exclusion_reason(7, [self._ask()])
        self.assertIn("needs-owner", reason)
        self.assertIn("awaiting owner answer", reason)

    def test_ask_by_another_loop_also_parks(self):
        self._exclusion_reason(7, [self._ask(loop="qa-loop")])

    def test_label_without_findable_ask_stays_parked(self):
        reason = self._exclusion_reason(7, [])
        self.assertIn("needs-owner", reason)

    def test_owner_answer_after_ask_makes_it_a_candidate(self):
        comments = [
            self._ask(),
            self._reply("human-owner", "2026-11-02T00:00:00Z", association="OWNER"),
        ]
        result = filter_and_rank_issues(
            [self._issue(7, ["needs-owner"])], [], self.me,
            config={}, issue_comments={7: comments},
        )
        self.assertEqual([c["number"] for c in result["candidates"]], [7])
        self.assertEqual(result["excluded"], [])

    def test_marker_comment_after_the_ask_does_not_unpark(self):
        comments = [
            self._ask(),
            {
                "body": "<!-- worker-loop: response round=2 -->\n\nStill waiting on this.",
                "createdAt": "2026-11-02T00:00:00Z",
                "author": {"login": self.me},
                "url": "https://example.test/c/response",
            },
        ]
        self._exclusion_reason(7, comments)

    def test_reply_before_the_ask_does_not_unpark(self):
        comments = [
            self._reply("human-owner", "2026-10-31T00:00:00Z", association="OWNER"),
            self._ask(createdAt="2026-11-01T00:00:00Z"),
        ]
        self._exclusion_reason(7, comments)

    def test_newer_ask_re_parks_after_an_earlier_answer(self):
        comments = [
            self._ask(createdAt="2026-11-01T00:00:00Z"),
            self._reply("human-owner", "2026-11-02T00:00:00Z", association="OWNER"),
            self._ask(createdAt="2026-11-03T00:00:00Z"),
        ]
        self._exclusion_reason(7, comments)


class BlockedOnClosureTest(unittest.TestCase):
    def test_merged_child_via_parent_surfaces_needs_closure_and_unblocks_wait_status(self):
        issues = [
            _issue(10, "Child feature"),
            _issue(11, "Depends on #10"),
        ]
        merged_prs = [
            _pr(100, "feat/parent-1", base="main", body="Fixes #1"),
            _pr(101, "feat/child-10", base="feat/parent-1", body="Fixes #10"),
        ]
        result = filter_and_rank_issues(issues, [], "me", config={}, merged_prs=merged_prs)

        # #10 is reported in needsClosure and excluded with an explicit closure reason.
        self.assertEqual([n["issue"] for n in result["needsClosure"]], [10])
        excluded_by_num = {e["number"]: e for e in result["excluded"]}
        self.assertIn(10, excluded_by_num)
        self.assertIn("close #10", excluded_by_num[10]["reason"])

        # #11 depends on #10: reported as blocked-on-closure rather than plain wait.
        by_num = {c["number"]: c for c in result["candidates"]}
        dep = by_num[11]["dependency"]
        self.assertEqual(dep["status"], "blocked-on-closure")
        self.assertEqual(dep["open"], [10])
        self.assertEqual([b["issue"] for b in dep["blockedOnClosure"]], [10])


